std::vector<uint8_t> base64_decode(const std::string& in) {
    std::vector<uint8_t> out;
    if (in.empty()) return out;
    size_t pad = 0;
    if (in.size() >= 1 && in.back() == '=') pad++;
    if (in.size() >= 2 && in[in.size()-2] == '=') pad++;
    size_t n = (in.size() * 3) / 4;
    if (pad > 0 && n > 0) n -= pad;
    out.reserve(n);
    unsigned int buf = 0;
    int bits = 0;
    for (unsigned char c : in) {
        if (c == '=') break;
        unsigned char d = kDecodeTable[c];
        if (d == 255) continue;
        buf = (buf << 6) | d;
        bits += 6;
        if (bits >= 8) {
            bits -= 8;
            out.push_back(static_cast<uint8_t>((buf >> bits) & 0xff));
        }
    }
    return out;
}

